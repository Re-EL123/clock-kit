export function icon(name, { size = 20, className = '', stroke = 2 } = {}) {
  const node = ICONS[name] || Clock;
  return createElement(node, {
    width: String(size),
    height: String(size),
    class: `ck-icon ${className}`.trim(),
    'stroke-width': String(stroke),
    'aria-hidden': 'true',
  });
}

export function viewIcon(view, opts) {
  return icon(VIEW_ICONS[view] || 'clock', opts);
}
